import 'model_tier.dart';

/// Represents the mapping between a specific video beat and a syllabus topic.
class VideoTopicMapping {
  final int videoIndex;
  final String videoTitle;
  final String? matchedTopicId;
  final String? matchedTopicTitle;
  final double confidence;
  final bool isMentorExtra;

  const VideoTopicMapping({
    required this.videoIndex,
    required this.videoTitle,
    this.matchedTopicId,
    this.matchedTopicTitle,
    required this.confidence,
    required this.isMentorExtra,
  });

  Map<String, dynamic> toJson() => {
        'videoIndex': videoIndex,
        'videoTitle': videoTitle,
        'matchedTopicId': matchedTopicId,
        'matchedTopicTitle': matchedTopicTitle,
        'confidence': confidence,
        'isMentorExtra': isMentorExtra,
      };
}

/// Represents a contiguous chronological milestone of mentor videos (e.g. Videos 0..7).
class ContiguousMilestone {
  final String title;
  final int startIndex;
  final int endIndex;

  const ContiguousMilestone({
    required this.title,
    required this.startIndex,
    required this.endIndex,
  });

  Map<String, dynamic> toJson() => {
        'title': title,
        'startIndex': startIndex,
        'endIndex': endIndex,
      };
}

/// Comprehensive audit output generated by the AI Model / Inference engine
/// comparing a Subject's benchmark syllabus against an attached playlist.
class CurriculumAuditResult {
  final String subjectTitle;
  final List<String> orderedSyllabusTopics;
  final List<String> coveredTopics;
  final List<String> uncoveredGaps;
  final List<String> mentorExtras;
  final List<VideoTopicMapping> mappings;
  final List<ContiguousMilestone> milestones;
  final double coveragePercentage;
  final String auditSummaryMarkdown;
  final ModelTier evaluatedTier;

  const CurriculumAuditResult({
    required this.subjectTitle,
    required this.orderedSyllabusTopics,
    required this.coveredTopics,
    required this.uncoveredGaps,
    required this.mentorExtras,
    required this.mappings,
    this.milestones = const [],
    required this.coveragePercentage,
    required this.auditSummaryMarkdown,
    required this.evaluatedTier,
  });

  bool get hasGaps => uncoveredGaps.isNotEmpty;
  int get totalSyllabusTopics => coveredTopics.length + uncoveredGaps.length;

  Map<String, dynamic> toJson() => {
        'subjectTitle': subjectTitle,
        'orderedSyllabusTopics': orderedSyllabusTopics,
        'coveredTopics': coveredTopics,
        'uncoveredGaps': uncoveredGaps,
        'mentorExtras': mentorExtras,
        'mappings': mappings.map((m) => m.toJson()).toList(),
        'milestones': milestones.map((m) => m.toJson()).toList(),
        'coveragePercentage': coveragePercentage,
        'auditSummaryMarkdown': auditSummaryMarkdown,
        'evaluatedTier': evaluatedTier.name,
      };
}
